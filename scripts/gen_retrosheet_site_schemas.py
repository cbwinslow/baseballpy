"""Generate ``sources/retrosheet/site_tables.py``: strict column types of the Retrosheet site datasets.

Reads the stored zips in ``raw/retrosheet/site_files/`` (fetch them first with ``baseballpy ingest retrosheet -d
transactions`` ...), infers every column's type over every value, checks the declared key and writes the generated
module. Types come from the data, never from column names: members are read in batches, each batch is typed with
whole-column Arrow casts (int16, int32, int64, float64, else text; a batch with no value gives no evidence) and the
batch types are widened. A declared date column is ``date32`` only when every value is a valid ``YYYYMMDD`` date; a
declared text column stays text (partial dates keep the upstream text).

Usage: ``uv run python scripts/gen_retrosheet_site_schemas.py [--home DIR] [--out FILE]``
"""

import argparse
import zipfile
from pathlib import Path

import pyarrow as pa
import pyarrow.compute as pc

from baseballpy.core.config import LakeConfig
from baseballpy.core.schema_tools import read_csv_strings, snake
from baseballpy.core.stores import RawStore
from baseballpy.sources.retrosheet import site

DEFAULT_OUT = "src/baseballpy/sources/retrosheet/site_tables.py"
_VALID_DATE = r"^(18|19|20)\d{2}(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])$"
_RANK = {"int16": 0, "int32": 1, "int64": 2, "float64": 3, "string": 4}
#: whole numbers with a leading zero are codes, not numbers
_LEADING_ZERO = "^-?0[0-9]"
#: member files read at once
BATCH_MEMBERS = 400


def _present(column: pa.Array | pa.ChunkedArray) -> pa.Array | pa.ChunkedArray:
    return pc.filter(column, pc.and_(pc.is_valid(column), pc.not_equal(column, "")))


def infer_arrow_type(column: pa.Array | pa.ChunkedArray, *, numeric: bool = False) -> str | None:
    """Type name of a text column from all its values (``None`` when no value is present).

    A ``numeric`` column is typed from the values that are numbers: a stray non-number does not make it text (the
    loader quarantines that cell).
    """
    values = _present(column)
    if numeric and len(values):
        values = pc.filter(values, pc.match_substring_regex(values, r"^-?[0-9]+(\.[0-9]+)?$"))
    if len(values) == 0:
        return None
    if pc.any(pc.match_substring_regex(values, _LEADING_ZERO)).as_py():
        return "string"
    try:
        whole = pc.cast(values, pa.int64())
    except pa.ArrowInvalid:
        try:
            pc.cast(values, pa.float64())
        except pa.ArrowInvalid:
            return "string"
        return "float64"
    low, high = pc.min_max(whole).as_py().values()
    if low >= -20000 and high <= 20000:
        return "int16"
    if low >= -(2**31) and high < 2**31:
        return "int32"
    return "int64"


def widen_types(a: str | None, b: str | None) -> str | None:
    """The wider of two type names; ``None`` (no evidence) never widens."""
    if a is None:
        return b
    if b is None:
        return a
    return a if _RANK[a] >= _RANK[b] else b


def _all_valid_dates(column: pa.Array | pa.ChunkedArray) -> bool:
    values = _present(column)
    return len(values) == 0 or bool(pc.all(pc.match_substring_regex(values, _VALID_DATE)).as_py())


def _members(archive: zipfile.ZipFile, spec: site.SiteDataset) -> list[str]:
    if spec.suffix:
        return sorted(n for n in archive.namelist() if n.endswith(spec.suffix))
    return [spec.member]


def _table(archive: zipfile.ZipFile, spec: site.SiteDataset, member: str) -> pa.Table:
    """One member as a text table, with the id column from its file name when the dataset says so."""
    header = spec.header.split(",") if spec.header else None
    table = read_csv_strings(archive.read(member), header=header)
    if spec.id_column:
        stem = member.rsplit("/", 1)[-1].removesuffix(spec.suffix)
        table = table.append_column(spec.id_column, pa.array([stem] * table.num_rows, pa.string()))
    return table


def render(config: LakeConfig) -> str:
    """Python source of the generated module."""
    raw = RawStore(config)
    out = [
        '"""GENERATED by scripts/gen_retrosheet_site_schemas.py from the Retrosheet site files. Do not edit.',
        "",
        "``SITE_COLUMNS`` maps dataset -> ((column, type_name, upstream_header), ...) in the shape of",
        '``tables.RETROSHEET_COLUMNS``; ``SITE_KEYS`` documents each key."""',
        "",
        "SITE_COLUMNS: dict[str, tuple[tuple[str, str, str], ...]] = {",
    ]
    keys: dict[str, tuple[str, ...]] = {}
    for dataset, spec in site.SITE_DATASETS.items():
        renames = dict(spec.renames)
        types: dict[str, str | None] = {}
        dates_ok: dict[str, bool] = {}
        upstream: dict[str, str] = {}
        key_rows: set[tuple[object, ...]] = set()
        rows = 0
        path = raw.path_for("retrosheet", site.RAW_DATASET, spec.zip_name)
        with zipfile.ZipFile(path) as archive:
            members = _members(archive, spec)
            for start in range(0, len(members), BATCH_MEMBERS):
                parts = [_table(archive, spec, m) for m in members[start : start + BATCH_MEMBERS]]
                joined = pa.concat_tables(parts, promote_options="default")
                rows += joined.num_rows
                names = {renames.get(c, snake(c) or c): c for c in joined.column_names}
                for name, raw_name in names.items():
                    upstream.setdefault(name, raw_name)
                    column = joined.column(raw_name)
                    types[name] = widen_types(
                        types.get(name), infer_arrow_type(column, numeric=name in spec.numeric)
                    )
                    if name in spec.dates:
                        dates_ok[name] = dates_ok.get(name, True) and _all_valid_dates(column)
                if missing := [k for k in spec.key if k not in names]:
                    raise SystemExit(f"{dataset}: key columns {missing} are not in the files")
                key_cols = [joined.column(names[k]).to_pylist() for k in spec.key]
                key_rows.update(zip(*key_cols, strict=True))
        out.append(
            f'    "{dataset}": (  # {rows:,} rows from {len(members):,} file(s) of {spec.zip_name}'
        )
        for name, type_name in types.items():
            if name in spec.text:
                final = "string"
            elif name in spec.dates:
                final = (
                    "date32:%Y%m%d" if dates_ok.get(name) and type_name is not None else "string"
                )
            else:
                final = (
                    type_name or "string"
                )  # an all-empty column: text keeps whatever it may hold later
            out.append(f'        ("{name}", "{final}", "{upstream[name]}"),')
        out.append("    ),")
        keys[dataset] = spec.key
        print(
            f"{dataset:22s} rows={rows:>9,} files={len(members):>6,} key={spec.key} "
            f"rows_beyond_a_unique_key={rows - len(key_rows)}"
        )
    out.append("}")
    out.append("")
    out.append("SITE_KEYS: dict[str, tuple[str, ...]] = {")
    out.extend(f'    "{name}": {key!r},' for name, key in keys.items())
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--home", default=None)
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args()
    config = LakeConfig(home=args.home) if args.home else LakeConfig()
    text = render(config)
    Path(args.out).write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
