"""Generate strict column schemas from real upstream CSV headers (dev tool, not a runtime dependency).

Usage::

    uv run python scripts/gen_schemas.py lahman <dir-with-csvs> [--out src/baseballpy/sources/lahman/tables.py]
    uv run python scripts/gen_schemas.py csv <file.csv> [more.csv ...]

Types are inferred over the *full* file with :func:`baseballpy.core.schema_tools.infer_type_name`
(conservative narrowing: never ``int8``; ``int16`` only when every value is within +-20000).
For ``lahman`` the candidate primary keys are checked for uniqueness and reported.
"""

