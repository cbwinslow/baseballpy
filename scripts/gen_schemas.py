def render_chadwick(directory: Path) -> str:
    """Python source for ``sources/chadwick/tables.py`` (shards are concatenated)."""
    import pyarrow as pa

    out = [
        '"""GENERATED by scripts/gen_schemas.py from the real Chadwick register headers. Do not edit.',
        "",
        "``CHADWICK_COLUMNS`` maps dataset -> ((column, type_name), ...) in upstream header order;",
        '``CHADWICK_KEYS`` documents each dataset key (uniqueness verified on the full data)."""',
        "",
        "CHADWICK_COLUMNS: dict[str, tuple[tuple[str, str], ...]] = {",
    ]
    keys: dict[str, tuple[str, ...]] = {}
    for dataset, pattern in CHADWICK_FILES.items():
        files = sorted(directory.glob(pattern))
        table = pa.concat_tables([read_csv_strings(f.read_bytes()) for f in files])
        columns = [
            (name, infer_type_name(table.column(name).to_pylist())) for name in table.column_names
        ]
        out.append(f'    "{dataset}": (  # {table.num_rows:,} rows from {len(files)} file(s)')
        out.extend(f'        ("{col}", "{type_name}"),' for col, type_name in columns)
        out.append("    ),")
        key = CHADWICK_CANDIDATE_KEYS[dataset]
        grouped = table.group_by(list(key)).aggregate([([key[0]], "count")])
        counts = grouped.column(grouped.num_columns - 1)
        dupes = int(pc.sum(pc.subtract(counts, 1)).as_py() or 0)
        keys[dataset] = key
        print(
            f"{dataset:20s} rows={table.num_rows:>8,} key={key} duplicates={dupes}", file=sys.stderr
        )
    out.append("}")
    out.append("")
    out.append("CHADWICK_KEYS: dict[str, tuple[str, ...]] = {")
    out.extend(f'    "{name}": {key!r},' for name, key in keys.items())
    out.append("}")
    return "\n".join(out) + "\n"


