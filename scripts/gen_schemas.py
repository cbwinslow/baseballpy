def profile(path: Path) -> tuple[list[tuple[str, str]], int]:
    """``([(column, type_name)], row_count)`` for one CSV."""
    table = read_csv_strings(path.read_bytes())
    columns = [
        (name, infer_type_name(table.column(name).to_pylist())) for name in table.column_names
    ]
    return columns, table.num_rows


def duplicate_count(path: Path, key: tuple[str, ...]) -> int | None:
    """Rows whose key tuple is not unique (``None`` when a key column is missing)."""
    table = read_csv_strings(path.read_bytes())
    lower = {n.lower(): n for n in table.column_names}
    cols = [lower.get(k.lower()) for k in key]
    if any(c is None for c in cols):
        return None
    grouped = table.group_by([c for c in cols if c]).aggregate([([cols[0] or ""], "count")])
    counts = grouped.column(grouped.num_columns - 1)
    return int(pc.sum(pc.subtract(counts, 1)).as_py() or 0)


def render_lahman(directory: Path) -> str:
    """Python source for ``sources/lahman/tables.py``."""
    out = [
        '"""GENERATED by scripts/gen_schemas.py from the real Lahman CSV headers. Do not edit by hand.',
        "",
        "``LAHMAN_COLUMNS`` maps table -> ((column, type_name), ...) in upstream header order;",
        '``LAHMAN_KEYS`` documents each table\'s primary key (uniqueness verified on the full data)."""',
        "",
        "LAHMAN_COLUMNS: dict[str, tuple[tuple[str, str], ...]] = {",
    ]
    keys: dict[str, tuple[str, ...]] = {}
    for path in sorted(directory.glob("*.csv")):
        columns, rows = profile(path)
        name = path.stem
        out.append(f'    "{name}": (  # {rows:,} rows')
        out.extend(f'        ("{col}", "{type_name}"),' for col, type_name in columns)
        out.append("    ),")
        candidate = LAHMAN_CANDIDATE_KEYS.get(name, ())
        dupes = duplicate_count(path, candidate) if candidate else None
        header_names = {c for c, _ in columns}
        resolved = tuple(
            next((h for h in header_names if h.lower() == k.lower()), k) for k in candidate
        )
        keys[name] = resolved
        print(f"{name:22s} rows={rows:>8,} key={resolved} duplicates={dupes}", file=sys.stderr)
    out.append("}")
    out.append("")
    out.append("LAHMAN_KEYS: dict[str, tuple[str, ...]] = {")
    out.extend(f'    "{name}": {key!r},' for name, key in keys.items())
    out.append("}")
    return "\n".join(out) + "\n"


