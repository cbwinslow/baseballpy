"""Cross-check every MLB endpoint route in the registry against the reference documents.

Writes ``docs/references/ENDPOINT_CROSSCHECK.md``: for each distinct route the registry fetches, which
of the cloned or excerpted references mention it (OpenAPI excerpt, MLB-StatsAPI, python-mlb-statsapi,
pybaseball, baseballr). A route no reference mentions is listed as "found live only". The references
describe parameters, not response column types, so column types stay confirmed by the live-probed
samples (``docs/mlb_probe.json`` and ``tests/fixtures/mlb``); this script says so rather than guess.

    uv run python scripts/endpoint_crosscheck.py [--check]
"""

import argparse
import re
import sys
from pathlib import Path

from baseballpy.sources.mlb_api.endpoints import ENDPOINTS

ROOT = Path(__file__).resolve().parent.parent
REFERENCES = {
    "OpenAPI": "mlb-stats-api-openapi.txt",
    "MLB-StatsAPI": "mlb-statsapi.txt",
    "python-mlb-statsapi": "python-mlb-statsapi.txt",
    "pybaseball": "pybaseball.txt",
    "baseballr": "baseballr.txt",
}
OUT = ROOT / "docs" / "references" / "ENDPOINT_CROSSCHECK.md"
_PLACEHOLDER = re.compile(r"\{[^}]*\}")


def route_key(path: str) -> str:
    """The route with every placeholder replaced by ``{}`` (references name placeholders differently)."""
    return _PLACEHOLDER.sub("{}", path.strip("/"))


def mentions(text: str, route: str) -> bool:
    """Whether ``text`` names the route, comparing with placeholders blanked out."""
    normalised = _PLACEHOLDER.sub("{}", text)
    for candidate in (route, "/" + route.removeprefix("v1/").removeprefix("v1.1/")):
        # the route must end where the name ends: "v1/teams" is not "v1/teams/stats"
        if re.search(re.escape(candidate) + r"(?![A-Za-z0-9_/{}])", normalised):
            return True
    return False


def build() -> str:
    """The Markdown report."""
    texts = {
        name: (ROOT / "docs" / "references" / file).read_text(encoding="utf-8", errors="replace")
        for name, file in REFERENCES.items()
    }
    routes: dict[str, list[str]] = {}
    for endpoint in ENDPOINTS:
        routes.setdefault(route_key(endpoint.path), []).append(endpoint.name)
    lines = [
        "# Endpoint cross-check (generated by `scripts/endpoint_crosscheck.py`)",
        "",
        f"{len(ENDPOINTS)} registry endpoints use {len(routes)} distinct routes. A cell marks the "
        "references that name the route (placeholders compared blanked out). Parameters are what the "
        "references document; they do not document response column types, so every column type is "
        "confirmed by the live-probed samples (`docs/mlb_probe.json`, `tests/fixtures/mlb`), not by "
        "these documents. Matching is textual, so a route a reference spells in another way (a "
        "version placeholder, a method name) is listed as found live only.",
        "",
        "| Route | Datasets | " + " | ".join(REFERENCES) + " |",
        "|---|---|" + "---|" * len(REFERENCES),
    ]
    live_only: list[str] = []
    for route, names in sorted(routes.items()):
        marks = [("yes" if mentions(text, route) else "-") for text in texts.values()]
        if "yes" not in marks:
            live_only.append(route)
        shown = ", ".join(names[:3]) + (f" (+{len(names) - 3})" if len(names) > 3 else "")
        lines.append(f"| `{route}` | {shown} | " + " | ".join(marks) + " |")
    lines += [
        "",
        f"## Found live only ({len(live_only)} routes no reference names)",
        "",
        *(f"- `{route}`" for route in live_only),
        "",
        "Disagreements between a reference and the live data: none are recorded by this script; "
        "a route listed above that a reference names but the live API refuses would appear in "
        "`docs/mlb_probe.json` as `unsupported` with the evidence.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    """Write the report, or with ``--check`` fail when the committed file is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run scripts/endpoint_crosscheck.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
