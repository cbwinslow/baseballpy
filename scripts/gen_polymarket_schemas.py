"""Generate ``sources/polymarket/tables.py`` by probing the live Polymarket API.

Types come from the data, never from column names: every key seen in the sampled records gets the
narrowest exact type that holds every sampled value (decimal text and short JSON numbers become
``decimal(P,S)``, ISO times ``timestamp``, nested values JSON text). Run it again when
``schema_drift`` warnings appear.

    uv run python scripts/gen_polymarket_schemas.py [--pages N] [--tokens N] [--check]
"""

import argparse
import json
import sys
import time
from collections import defaultdict
from pathlib import Path
from typing import Any

from baseballpy.core.infer_types import infer
from baseballpy.core.rawlog import RawLog
from baseballpy.sources.polymarket.extractor import PolymarketExtractor
from baseballpy.sources.polymarket.records import (
    outcome_rows,
    raw_price_window,
    snake_keys,
    split_event,
    windows,
)

OUTPUT = Path(__file__).resolve().parent.parent / "src/baseballpy/sources/polymarket/tables.py"


def render(columns: dict[str, dict[str, str]], meta: dict[str, dict[str, int]]) -> str:
    """The generated module text (deterministic: columns sorted by name)."""
    lines = [
        '"""Generated by scripts/gen_polymarket_schemas.py from live probes. Do not edit by hand."""',
        "",
        "from baseballpy.core.schema_tools import ColumnDef",
        "",
        "POLYMARKET_COLUMNS: dict[str, list[ColumnDef]] = {",
    ]
    for dataset in sorted(columns):
        lines.append(f"    {dataset!r}: [")
        lines += [
            f"        ({name!r}, {kind!r})," for name, kind in sorted(columns[dataset].items())
        ]
        lines.append("    ],")
    lines += ["}", "", "#: records probed per dataset (evidence for the types above)"]
    lines.append(f"POLYMARKET_META: dict[str, dict[str, int]] = {json.dumps(meta, sort_keys=True)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Probe, infer and write (or check) the generated module."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--pages", type=int, default=0, help="pages of 100 events to sample (0: all of them)"
    )
    parser.add_argument(
        "--tokens", type=int, default=60, help="outcome tokens whose prices to sample"
    )
    parser.add_argument("--check", action="store_true", help="exit 1 when tables.py is stale")
    args = parser.parse_args()

    extractor = PolymarketExtractor(store_raw=False)
    raw = RawLog()
    tag = extractor.sport_tag_id(raw)
    print(f"sport tag {tag}", flush=True)

    events: list[dict[str, Any]] = []
    markets: list[dict[str, Any]] = []
    for count, page in enumerate(extractor.events(tag, raw), start=1):
        for event in page:
            plain, inner = split_event(event)
            events.append(plain)
            markets.extend(inner)
        if args.pages and count >= args.pages:
            break
    outcomes = [row for market in markets for row in outcome_rows(market)]
    print(f"{len(events)} events, {len(markets)} markets, {len(outcomes)} outcomes", flush=True)

    now = int(time.time())
    prices: list[dict[str, Any]] = []
    closed = [m for m in markets if m.get("closed") and m.get("clobTokenIds")]
    step = max(1, len(closed) // max(1, args.tokens // 2))
    for market in closed[::step][: args.tokens // 2]:
        window = raw_price_window(market, now)
        if window is None:
            continue
        for row in outcome_rows(market):
            for index, (start, end) in enumerate(windows(*window)):
                prices.extend(extractor.price_history(row["tokenId"], start, end, raw, index))
    print(f"{len(prices)} price points", flush=True)

    records: dict[str, list[dict[str, Any]]] = defaultdict(list)
    records["events"], records["markets"] = events, markets
    records["outcomes"], records["prices"] = outcomes, prices
    columns: dict[str, dict[str, str]] = {}
    meta: dict[str, dict[str, int]] = {}
    for dataset, rows in records.items():
        shaped = [snake_keys(r) for r in rows]
        keys = sorted({k for r in shaped for k in r})
        columns[dataset] = {
            k: infer([r.get(k) for r in shaped], floats_as_decimal=True) for k in keys
        }
        meta[dataset] = {"records": len(rows)}
    text = render(columns, meta)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        stale = current != text
        print("tables.py is stale" if stale else "tables.py is current")
        return 1 if stale else 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
