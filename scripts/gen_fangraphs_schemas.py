"""Generate ``sources/fangraphs/tables.py`` from the files in ``inbox/fangraphs/``.

Types come from the data, never from column names: every header gets the narrowest exact type that
holds every value of the whole file. Numbers with more than 8 decimals or in scientific notation are
computed values (rates, model outputs) and become ``float64``. No network is used.

    uv run python scripts/gen_fangraphs_schemas.py [--check]
"""

import argparse
import csv
import gzip
import io
import json
import sys
from pathlib import Path

import pyarrow as pa
import pyarrow.csv as pacsv

from baseballpy.core.config import LakeConfig
from baseballpy.core.infer_types import infer
from baseballpy.sources.fangraphs.files import FILES

OUTPUT = Path(__file__).resolve().parent.parent / "src/baseballpy/sources/fangraphs/tables.py"
MAX_TEXT_SCALE = 8


def _read(data: bytes) -> pa.Table:
    """Every column as text, empty cells as NULL."""
    header = data.split(b"\n", 1)[0].decode("utf-8-sig")
    names = next(csv.reader([header]))
    return pacsv.read_csv(
        io.BytesIO(data),
        parse_options=pacsv.ParseOptions(newlines_in_values=True),  # scouting reports span lines
        convert_options=pacsv.ConvertOptions(
            column_types=dict.fromkeys(names, pa.string()),
            strings_can_be_null=True,
            null_values=[""],
        ),
    )


def render(columns: dict[str, dict[str, str]], meta: dict[str, dict[str, int]]) -> str:
    """The generated module text (columns in the file's own order)."""
    lines = [
        '"""Generated by scripts/gen_fangraphs_schemas.py from the files. Do not edit by hand."""',
        "",
        "from baseballpy.core.schema_tools import ColumnDef",
        "",
        "FANGRAPHS_COLUMNS: dict[str, list[ColumnDef]] = {",
    ]
    for dataset in sorted(columns):
        lines.append(f"    {dataset!r}: [")
        lines += [f"        ({name!r}, {kind!r})," for name, kind in columns[dataset].items()]
        lines.append("    ],")
    lines += ["}", "", "#: rows and columns read per dataset (evidence for the types above)"]
    lines.append(f"FANGRAPHS_META: dict[str, dict[str, int]] = {json.dumps(meta, sort_keys=True)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Read the inbox files, infer, and write (or check) the generated module."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when tables.py is stale")
    args = parser.parse_args()
    inbox = LakeConfig().inbox_dir("fangraphs")
    columns: dict[str, dict[str, str]] = {}
    meta: dict[str, dict[str, int]] = {}
    for file in FILES:
        path = next((inbox / n for n in file.names if (inbox / n).exists()), None)
        if path is None:
            print(f"missing {file.dataset}: put {file.names[0]} in {inbox}", file=sys.stderr)
            return 2
        table = _read(
            gzip.decompress(path.read_bytes()) if path.suffix == ".gz" else path.read_bytes()
        )
        columns[file.dataset] = {
            name: infer(table[name].drop_null().to_pylist(), max_text_scale=MAX_TEXT_SCALE)
            for name in table.column_names
        }
        meta[file.dataset] = {"rows": table.num_rows, "columns": table.num_columns}
        print(f"{file.dataset}: {table.num_rows} rows, {table.num_columns} columns", flush=True)
    text = render(columns, meta)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        stale = current != text
        print("tables.py is stale" if stale else "tables.py is current")
        return 1 if stale else 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
