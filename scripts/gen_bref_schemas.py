"""Generate ``sources/bref/tables.py`` from the real Baseball-Reference WAR files.

Types come from the data, never from column names: every header gets the narrowest exact type that
holds every value of the whole file (the files are small enough to read completely). The files are
downloaded through the shared client (6 requests a minute at most, kept in ``raw/``); a file
downloaded in the last 12 hours is reused, so a rerun asks for nothing.

    uv run python scripts/gen_bref_schemas.py [--check]
"""

import argparse
import csv
import io
import json
import sys
from pathlib import Path

from baseballpy.core.infer_types import infer
from baseballpy.sources.bref.endpoints import FILES, NULL_TOKEN
from baseballpy.sources.bref.extractor import BrefExtractor

OUTPUT = Path(__file__).resolve().parent.parent / "src/baseballpy/sources/bref/tables.py"


def render(columns: dict[str, dict[str, str]], meta: dict[str, dict[str, int]]) -> str:
    """The generated module text (columns in the file's own order)."""
    lines = [
        '"""Generated by scripts/gen_bref_schemas.py from the real files. Do not edit by hand."""',
        "",
        "from baseballpy.core.schema_tools import ColumnDef",
        "",
        "BREF_COLUMNS: dict[str, list[ColumnDef]] = {",
    ]
    for dataset in sorted(columns):
        lines.append(f"    {dataset!r}: [")
        lines += [f"        ({name!r}, {kind!r})," for name, kind in columns[dataset].items()]
        lines.append("    ],")
    lines += ["}", "", "#: rows read per dataset (evidence for the types above)"]
    lines.append(f"BREF_META: dict[str, dict[str, int]] = {json.dumps(meta, sort_keys=True)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Read the files, infer, and write (or check) the generated module."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when tables.py is stale")
    args = parser.parse_args()
    extractor = BrefExtractor()
    columns: dict[str, dict[str, str]] = {}
    meta: dict[str, dict[str, int]] = {}
    for file in FILES:
        text = extractor.fetch(file).decode("utf-8")
        rows = list(csv.reader(io.StringIO(text, newline="")))
        header, body = rows[0], rows[1:]
        columns[file.dataset] = {
            name: infer([r[i] for r in body if r[i] not in ("", NULL_TOKEN)])
            for i, name in enumerate(header)
        }
        meta[file.dataset] = {"rows": len(body), "columns": len(header)}
        print(f"{file.dataset}: {len(body)} rows, {len(header)} columns", flush=True)
    text = render(columns, meta)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        stale = current != text
        print("tables.py is stale" if stale else "tables.py is current")
        return 1 if stale else 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
